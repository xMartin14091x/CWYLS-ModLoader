class SigReader:
    """Reads a signature blob: compressed integers, type-def-or-ref tokens, bytes."""

    def __init__(self, blob):
        self.b = blob
        self.p = 0

    def byte(self):
        value = self.b[self.p]
        self.p += 1
        return value

    def peek(self):
        return self.b[self.p]

    def uint(self):
        b0 = self.byte()
        if b0 & 0x80 == 0:
            return b0
        if b0 & 0xC0 == 0x80:
            return ((b0 & 0x3F) << 8) | self.byte()
        return ((b0 & 0x1F) << 24) | (self.byte() << 16) | (self.byte() << 8) | self.byte()

    def token(self):
        value = self.uint()
        return ([TYPEDEF, TYPEREF, TYPESPEC][value & 3], value >> 2)


class Metadata:
    """The metadata tables and heaps of one managed assembly, read from its bytes."""

    def __init__(self, path):
        with open(path, "rb") as handle:
            self.data = handle.read()
        self.path = path
        self._read_streams()
        self._read_tables()

    # -- PE and metadata root -------------------------------------------------------------

    def _u16(self, offset):
        return struct.unpack_from("<H", self.data, offset)[0]

    def _u32(self, offset):
        return struct.unpack_from("<I", self.data, offset)[0]

    def _read_streams(self):
        pe = self._u32(0x3C)
        if self.data[pe:pe + 4] != b"PE\0\0":
            raise ValueError(self.path + ": not a PE file")
        coff = pe + 4
        section_count = self._u16(coff + 2)
        optional_size = self._u16(coff + 16)
        optional = coff + 20
        magic = self._u16(optional)
        directories = optional + (96 if magic == 0x10B else 112)
        cli_rva = self._u32(directories + 14 * 8)
        if cli_rva == 0:
            raise ValueError(self.path + ": no CLI header (not a .NET assembly)")

        self._sections = []
        section = optional + optional_size
        for i in range(section_count):
            base = section + i * 40
            virtual_size, virtual_address, raw_size, raw_pointer = struct.unpack_from("<IIII", self.data, base + 8)
            self._sections.append((virtual_address, max(virtual_size, raw_size), raw_pointer))

        cli = self._offset(cli_rva)
        root = self._offset(self._u32(cli + 8))
        if self._u32(root) != 0x424A5342:
            raise ValueError(self.path + ": bad metadata signature")
        version_length = self._u32(root + 12)
        p = root + 16 + version_length
        stream_count = self._u16(p + 2)
        p += 4
        self.streams = {}
        for _ in range(stream_count):
            offset, size = struct.unpack_from("<II", self.data, p)
            end = self.data.index(b"\0", p + 8)
            name = self.data[p + 8:end].decode("ascii")
            self.streams[name] = (root + offset, size)
            p = p + 8 + ((len(name) + 1 + 3) & ~3)

    def _offset(self, rva):
        for virtual_address, size, raw_pointer in self._sections:
            if virtual_address <= rva < virtual_address + size:
                return raw_pointer + rva - virtual_address
        raise ValueError(self.path + ": RVA 0x%x is outside every section" % rva)

    # -- tables -----------------------------------------------------------------------------

    def _read_tables(self):
        if "#~" not in self.streams:
            raise ValueError(self.path + ": only compressed metadata (#~) is supported")
        start = self.streams["#~"][0]
        heap_sizes = self.data[start + 6]
        valid = struct.unpack_from("<Q", self.data, start + 8)[0]
        p = start + 24
        counts = [0] * 64
        for i in range(64):
            if valid >> i & 1:
                if i not in SCHEMA:
                    raise ValueError(self.path + ": unsupported metadata table 0x%02x" % i)
                counts[i] = self._u32(p)
                p += 4
        if heap_sizes & 0x40:
            p += 4
        self.counts = counts

        sizes = {
            STR: 4 if heap_sizes & 0x01 else 2,
            GUID: 4 if heap_sizes & 0x02 else 2,
            BLOB: 4 if heap_sizes & 0x04 else 2,
            U2: 2,
            U4: 4,
        }

        def column_size(column):
            if isinstance(column, str):
                return sizes[column]
            if column[0] == "t":
                return 2 if counts[column[1]] < (1 << 16) else 4
            bits, tables = CODED[column[1]]
            largest = max(counts[t] for t in tables if t is not None)
            return 2 if largest < (1 << (16 - bits)) else 4

        self.rows = {}
        for table in range(45):
            columns = SCHEMA[table]
            widths = [column_size(c) for c in columns]
            rows = []
            for _ in range(counts[table]):
                row = []
                for width in widths:
                    row.append(self._u16(p) if width == 2 else self._u32(p))
                    p += width
                rows.append(tuple(row))
            self.rows[table] = rows

        self._strings = self.streams["#Strings"][0]
        self._blobs = self.streams["#Blob"][0] if "#Blob" in self.streams else None

    def row(self, table, index):
        """One row, by its 1-based index."""
        return self.rows[table][index - 1]

    def string(self, index):
        start = self._strings + index
        return self.data[start:self.data.index(b"\0", start)].decode("utf-8")

    def blob(self, index):
        reader = SigReader(self.data)
        reader.p = self._blobs + index
        length = reader.uint()
        return self.data[reader.p:reader.p + length]

    @staticmethod
    def decode(coded, value):
        """A coded index as (table, 1-based row); row 0 means null."""
        bits, tables = CODED[coded]
        return tables[value & ((1 << bits) - 1)], value >> bits


# ---------------------------------------------------------------------------------------------
# Type nodes (decoded signatures) and their two spellings: documentation ID and C#-like text
# ---------------------------------------------------------------------------------------------
# ("prim", "System.Int32") · ("named", namespace, (name, nested, ...)) · ("gen", named, [args])
# ("arr", element, rank; 0 = single-dimension) · ("ref", element) · ("ptr", element)
# ("var", n) type parameter · ("mvar", n) method parameter

KEYWORDS = {
    "System.Void": "void", "System.Boolean": "bool", "System.Char": "char", "System.SByte": "sbyte",
    "System.Byte": "byte", "System.Int16": "short", "System.UInt16": "ushort", "System.Int32": "int",
    "System.UInt32": "uint", "System.Int64": "long", "System.UInt64": "ulong", "System.Single": "float",
    "System.Double": "double", "System.String": "string", "System.Object": "object",
    "System.Decimal": "decimal",
}

ARITY = re.compile(r"^(.*)`(\d+)$")


def qualified(named):
    namespace, names = named[1], named[2]
    return (namespace + "." if namespace else "") + ".".join(names)


def id_string(node):
    """The type as the C# compiler spells it inside a documentation ID."""
    kind = node[0]
    if kind == "prim":
        return node[1]
    if kind == "named":
        return qualified(node)
    if kind == "gen":
        base = node[1]
        args = [id_string(a) for a in node[2]]
        parts, used = [], 0
        for name in base[2]:
            match = ARITY.match(name)
            if match:
                count = int(match.group(2))
                parts.append(match.group(1) + "{" + ",".join(args[used:used + count]) + "}")
                used += count
            else:
                parts.append(name)
        return (base[1] + "." if base[1] else "") + ".".join(parts)
    if kind == "arr":
        return id_string(node[1]) + ("[]" if node[2] == 0 else "[" + ",".join(["0:"] * node[2]) + "]")
    if kind == "ref":
        return id_string(node[1]) + "@"
    if kind == "ptr":
        return id_string(node[1]) + "*"
    if kind == "var":
        return "`%d" % node[1]
    if kind == "mvar":
        return "``%d" % node[1]
    raise ValueError("unknown type node " + repr(node))


def strip_arity(name):
    match = ARITY.match(name)
    return match.group(1) if match else name


def display(node, type_params=(), method_params=()):
    """The type as a reader writes it in C#, without its namespace."""
    kind = node[0]
    if kind == "prim":
        return KEYWORDS.get(node[1], node[1].rsplit(".", 1)[-1])
    if kind == "named":
        name = qualified(node)
        if name in KEYWORDS:
            return KEYWORDS[name]
        return ".".join(strip_arity(n) for n in node[2])
    if kind == "gen":
        base = node[1]
        args = [display(a, type_params, method_params) for a in node[2]]
        name = qualified(base)
        if name == "System.Nullable`1":
            return args[0] + "?"
        if name.startswith("System.ValueTuple`"):
            return "(" + ", ".join(args) + ")"
        parts, used = [], 0
        for segment in base[2]:
            match = ARITY.match(segment)
            if match:
                count = int(match.group(2))
                parts.append(match.group(1) + "<" + ", ".join(args[used:used + count]) + ">")
                used += count
            else:
                parts.append(segment)
        return ".".join(parts)
    if kind == "arr":
        inner = display(node[1], type_params, method_params)
        return inner + ("[]" if node[2] == 0 else "[" + "," * (node[2] - 1) + "]")
    if kind == "ref":
        return "ref " + display(node[1], type_params, method_params)
    if kind == "ptr":
        return display(node[1], type_params, method_params) + "*"
    if kind == "var":
        return type_params[node[1]] if node[1] < len(type_params) else "T%d" % node[1]
    if kind == "mvar":
        return method_params[node[1]] if node[1] < len(method_params) else "M%d" % node[1]
    raise ValueError("unknown type node " + repr(node))


def referenced_names(node, into):
    """Collects the qualified names of every named type inside a node."""
    kind = node[0]
    if kind == "named":
        into.add(qualified(node))
    elif kind == "gen":
        into.add(qualified(node[1]))
        for arg in node[2]:
            referenced_names(arg, into)
    elif kind in ("arr", "ref", "ptr"):
        referenced_names(node[1], into)


