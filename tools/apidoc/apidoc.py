def build(dll_paths):
    assemblies = [Assembly(p) for p in dll_paths]
    for assembly in assemblies:
        assembly.collect_enums(ENUM_NAMES)
    for assembly in assemblies:
        assembly.build_types()
    docs = {}
    for path in dll_paths:
        xml_path = os.path.splitext(path)[0] + ".xml"
        if not os.path.isfile(xml_path):
            raise SystemExit("apidoc: no XML documentation next to " + path +
                             " (build with -p:GenerateDocumentationFile=true)")
        docs.update(load_xml(xml_path))
    return assemblies, docs


def api_version(assemblies):
    for assembly in assemblies:
        for info in assembly.types:
            if info.full_name == "CwyLs.ModLoader.Core.Mods.CwyApi":
                # VersionText is static readonly (no metadata constant); the const it is built from is.
                for name in ("VersionText", "PluginVersionText"):
                    for m in info.members:
                        if m.name == name and m.value:
                            return str(m.value[1])
    return "unknown"


def generate(dll_paths):
    """{file name: text} for the whole reference, plus the self-check problems."""
    assemblies, docs = build(dll_paths)
    reference = Reference(assemblies, docs)
    namespaces = reference.namespaces()
    files = {}
    for namespace, infos in namespaces.items():
        files[page_of(namespace)] = reference.render_namespace(namespace, infos)
    undocumented_text, total = reference.render_undocumented(namespaces)
    files["undocumented.md"] = undocumented_text
    files["README.md"] = reference.render_index(namespaces, api_version(assemblies), total)
    unknown = sorted(i for i in docs if not i.startswith("N:") and i not in reference.all_ids)
    return files, unknown, total


def main(argv):
    parser = argparse.ArgumentParser(description="Generate the CWY:LS Mod Loader API reference (Markdown).")
    parser.add_argument("assemblies", nargs="+", help="assembly DLLs; each needs its XML documentation file beside it")
    parser.add_argument("--out", required=True, help="output folder, normally docs/api")
    parser.add_argument("--check", action="store_true", help="write nothing; exit 1 when the folder differs from a fresh run")
    parser.add_argument("--strict", action="store_true", help="exit 1 when an XML entry matches no member (a generator bug)")
    args = parser.parse_args(argv)

    files, unknown, total = generate(args.assemblies)
    for doc_id in unknown:
        print("apidoc: XML entry matches no member in the metadata: " + doc_id, file=sys.stderr)

    stale = []
    if os.path.isdir(args.out):
        for name in sorted(os.listdir(args.out)):
            path = os.path.join(args.out, name)
            if name.endswith(".md") and name not in files and os.path.isfile(path):
                with open(path, encoding="utf-8") as handle:
                    if handle.readline().rstrip("\n") == GENERATED_MARKER:
                        stale.append(path)

    if args.check:
        different = []
        for name, text in sorted(files.items()):
            path = os.path.join(args.out, name)
            current = open(path, encoding="utf-8").read() if os.path.isfile(path) else None
            if current != text:
                different.append(name)
        for path in stale:
            different.append(os.path.basename(path) + " (no longer generated)")
        for name in different:
            print("apidoc: stale: " + name, file=sys.stderr)
        print("apidoc: %d page(s) checked, %d stale, %d undocumented item(s)" % (len(files), len(different), total))
        return 1 if different or (args.strict and unknown) else 0

    os.makedirs(args.out, exist_ok=True)
    written = 0
    for name, text in sorted(files.items()):
        path = os.path.join(args.out, name)
        current = open(path, encoding="utf-8").read() if os.path.isfile(path) else None
        if current != text:
            with open(path, "w", encoding="utf-8", newline="\n") as handle:
                handle.write(text)
            written += 1
    for path in stale:
        os.remove(path)
    print("apidoc: %d page(s), %d changed, %d removed, %d undocumented item(s), %d unmatched XML entr(ies) -> %s" %
          (len(files), written, len(stale), total, len(unknown), args.out))
    return 1 if args.strict and unknown else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
