KIND_ORDER = {"ctor": 0, "field": 1, "property": 2, "event": 3, "method": 4, "enumvalue": 5}


def anchor_of(*parts):
    text = "-".join(p for p in parts if p)
    text = re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")
    return text or "x"


def page_of(namespace):
    return (namespace or "global") + ".md"


class Reference:
    def __init__(self, assemblies, docs):
        self.assemblies = assemblies
        self.docs = docs
        self.links = Links()
        self.types = [t for a in assemblies for t in a.types if t.visible and not t.compiler_generated]
        self.types_by_name = {t.full_name: t for a in assemblies for t in a.types}
        self.all_ids = {t.doc_id for a in assemblies for t in a.types}
        for a in assemblies:
            for t in a.types:
                for m in t.members:
                    self.all_ids.add(m.doc_id)
        for t in self.types:
            self.links.type_names[t.full_name] = t.display_name
        self._assign_anchors()
        self.mod_api = self._mod_api_closure()

    # -- what gets rendered ---------------------------------------------------------------

    def shown_members(self, info):
        """Visible members worth a heading: no accessors, no compiler plumbing, no undocumented default constructors."""
        shown = []
        for m in info.members:
            if not m.visible or m.compiler_generated:
                continue
            if info.kind == "delegate":
                continue
            if m.kind == "ctor" and m.param_count == 0 and m.doc_id not in self.docs:
                continue
            shown.append(m)
        shown.sort(key=lambda m: (KIND_ORDER[m.kind], m.name.lower(), m.name, m.doc_id))
        return shown

    def _assign_anchors(self):
        used = set()
        for info in sorted(self.types, key=lambda t: t.doc_id):
            page = page_of(info.namespace)
            base = anchor_of(*[n.replace("`", "-") for n in info.names])
            anchor = base
            n = 2
            while (page, anchor) in used:
                anchor = base + "-" + str(n)
                n += 1
            used.add((page, anchor))
            info.anchor = anchor
            self.links.add(info.doc_id, page, anchor, info.display_name)
            members = self.shown_members(info)
            names = {}
            for m in members:
                names[m.name] = names.get(m.name, 0) + 1
            for m in members:
                label = "ctor" if m.kind == "ctor" else m.name
                extra = m.overload_key if names[m.name] > 1 else ""
                member_base = anchor + "--" + anchor_of(label, extra)
                member_anchor = member_base
                n = 2
                while (page, member_anchor) in used:
                    member_anchor = member_base + "-" + str(n)
                    n += 1
                used.add((page, member_anchor))
                m.anchor = member_anchor
                text = info.display_name + ("" if m.kind == "ctor" else "." + m.name)
                self.links.add(m.doc_id, page, member_anchor, text)
            if info.kind == "enum":
                for m in info.members:
                    if m.kind == "enumvalue" and m.visible:
                        m.anchor = anchor + "--" + anchor_of(m.name)
                        used.add((page, m.anchor))
                        self.links.add(m.doc_id, page, m.anchor, info.display_name + "." + m.name)

    def _mod_api_closure(self):
        """Types a mod reaches from CwyMod through public signatures, plus the types implementing them."""
        start = self.types_by_name.get("CwyLs.ModLoader.Mods.CwyMod")
        if start is None:
            return set()
        visible = {t.full_name: t for t in self.types}
        reached, queue = set(), [start.full_name]
        while queue:
            while queue:
                name = queue.pop()
                if name in reached or name not in visible:
                    continue
                reached.add(name)
                info = visible[name]
                names = set()
                for node in ([info.extends] if info.extends else []) + info.interfaces:
                    referenced_names(node, names)
                for m in self.shown_members(info) + [m for m in info.members if m.kind == "enumvalue"]:
                    for node in m.types:
                        referenced_names(node, names)
                queue.extend(sorted(names))
            # A mod also receives types it cannot name in a signature: the records behind
            # Subscribe<T> where T : ICwyEvent. Types deriving from or implementing a reached type
            # join, and their own signatures are followed in the next round.
            for other in sorted(visible):
                if other in reached:
                    continue
                bases = set()
                for node in ([visible[other].extends] if visible[other].extends else []) + visible[other].interfaces:
                    referenced_names(node, bases)
                if bases & reached:
                    queue.append(other)
        return reached

    # -- documentation of one item --------------------------------------------------------

    def doc_of(self, doc_id, info=None, member=None):
        """
        (element, unresolved) for an item. An <inheritdoc/> is followed to the member of our own
        assemblies it refers to; unresolved is "dotnet" when the source can only be a .NET member
        (System.Object, IEquatable, ...), "ours" when it is ours but undocumented, else "".
        """
        element = self.docs.get(doc_id)
        if element is None:
            return None, ""
        inherit = element.find("inheritdoc")
        if inherit is None:
            return element, ""
        source, unresolved = None, "ours"
        if inherit.get("cref"):
            source = self.docs.get(inherit.get("cref"))
        elif info is not None and member is not None:
            source, unresolved = self._inherited(info, member)
        if source is None:
            return element, unresolved
        merged = ET.Element("member")
        present = {child.tag for child in element if child.tag != "inheritdoc"}
        for child in element:
            if child.tag != "inheritdoc":
                merged.append(child)
        for child in source:
            if child.tag not in present:
                merged.append(child)
        return merged, ""

    def _inherited(self, info, member):
        """The documentation of the base or interface member with the same signature, searched in our assemblies."""
        prefix, _, rest = member.doc_id.partition(":")
        suffix = rest[len(info.full_name) + 1:]
        seen = set()
        pending = [info]
        ours = False
        while pending:
            current = pending.pop(0)
            candidates = []
            for node in ([current.extends] if current.extends else []) + current.interfaces:
                if node[0] == "named":
                    candidates.append(qualified(node))
            for name in candidates:
                if name in seen:
                    continue
                seen.add(name)
                candidate_id = prefix + ":" + name + "." + suffix
                found = self.docs.get(candidate_id)
                if found is not None and found.find("inheritdoc") is None:
                    return found, ""
                if candidate_id in self.all_ids:
                    ours = True
                if name in self.types_by_name:
                    pending.append(self.types_by_name[name])
        return None, ("ours" if ours else "dotnet")

    @staticmethod
    def deprecation(attributes):
        for name, args, named in attributes:
            if name == ATTR_CWY_DEPRECATED:
                since = args[0] if args else "?"
                stage = DEPRECATION_STAGES.get(args[1], str(args[1])) if len(args) > 1 else "?"
                text = "**Deprecated** since " + escape_text(str(since)) + " (" + stage + ")"
                if named.get("Replacement"):
                    text += ": use " + code_span(named["Replacement"]) + " instead"
                return text + "."
            if name == ATTR_OBSOLETE:
                text = "**Obsolete**"
                if args and args[0]:
                    text += ": " + escape_text(str(args[0]))
                return text
        return ""

    # -- pages ------------------------------------------------------------------------------

    def namespaces(self):
        grouped = {}
        for info in self.types:
            grouped.setdefault(info.namespace, []).append(info)
        for infos in grouped.values():
            infos.sort(key=lambda t: (t.display_name.lower(), t.doc_id))
        return dict(sorted(grouped.items()))

    def undocumented(self, info):
        missing = []
        if info.doc_id not in self.docs:
            missing.append(("type", info.display_name))
        for m in self.shown_members(info):
            if m.doc_id not in self.docs:
                missing.append((m.kind, m.signature if m.kind != "enumvalue" else m.name))
        if info.kind == "enum":
            for m in info.members:
                if m.kind == "enumvalue" and m.visible and m.doc_id not in self.docs:
                    missing.append(("enumvalue", m.name))
        return missing

    def render_namespace(self, namespace, infos):
        page = page_of(namespace)
        renderer = DocRenderer(self.links, page)
        plain = DocRenderer(self.links, page, plain=True)
        assemblies = sorted({t.assembly for t in infos})
        out = [GENERATED_MARKER, "", "# Namespace `" + (namespace or "(global)") + "`", ""]
        out.append("Assembly " + ", ".join(code_span(a) for a in assemblies) + " · " + str(len(infos)) +
                   " public type(s) · [API index](README.md)")
        out.append("")
        out.append("| Type | Kind | Summary |")
        out.append("|---|---|---|")
        for info in infos:
            element, _ = self.doc_of(info.doc_id)
            summary = first_sentence(plain.render(element.find("summary")) if element is not None else "")
            marks = " (mod API)" if info.full_name in self.mod_api else ""
            if self.deprecation(info.attributes):
                marks += " (deprecated)"
            out.append("| [" + code_span(info.display_name) + "](#" + info.anchor + ")" + marks + " | " + info.kind +
                       " | " + table_cell(summary) + " |")
        out.append("")
        for info in infos:
            out.extend(self.render_type(info, renderer))
        return "\n".join(out).rstrip("\n") + "\n"

    def render_type(self, info, renderer):
        out = ["---", "", '<a id="' + info.anchor + '"></a>', "", "## `" + info.display_name + "`", ""]
        facts = [info.kind, code_span(info.full_name), "assembly " + code_span(info.assembly)]
        if info.full_name in self.mod_api:
            facts.append("mod API")
        out.append(" · ".join(facts))
        out.append("")
        relations = []
        if info.extends and info.kind not in ("enum", "struct", "delegate"):
            base = qualified(info.extends[1] if info.extends[0] == "gen" else info.extends)
            if base != "System.Object":
                relations.append("Base: " + self._type_link(info.extends, info, renderer.page))
        if info.interfaces:
            label = "Extends" if info.kind == "interface" else "Implements"
            links = [self._type_link(i, info, renderer.page) for i in
                     sorted(info.interfaces, key=lambda n: display(n, info.generic_params))]
            relations.append(label + ": " + ", ".join(links))
        if info.generic_constraints:
            relations.append("Constraints: " + "; ".join(
                code_span(p + " : " + ", ".join(c)) for p, c in info.generic_constraints.items()))
        if relations:
            # Two trailing spaces end a Markdown line without starting a new paragraph.
            out.append("  \n".join(relations))
            out.append("")
        deprecated = self.deprecation(info.attributes)
        if deprecated:
            out.extend(["> " + deprecated, ""])
        if info.kind == "delegate" and info.delegate_invoke is not None:
            invoke = info.delegate_invoke.signature
            out.extend(["```csharp", "delegate " + invoke.replace(" Invoke(", " " + info.display_name + "(", 1), "```", ""])
        element, unresolved = self.doc_of(info.doc_id)
        out.extend(self.render_sections(element, renderer, unresolved))

        if info.kind == "enum":
            out.extend(self.render_enum(info, renderer))
        for m in self.shown_members(info):
            if m.kind == "enumvalue":
                continue
            out.extend(self.render_member(info, m, renderer))

        missing = self.undocumented(info)
        if missing:
            out.append("**Not documented yet:**")
            out.append("")
            for kind, text in missing:
                out.append("- " + code_span(text) + (" (" + kind + ")" if kind in ("type", "enumvalue") else ""))
            out.append("")
        return out

    def _type_link(self, node, info, page):
        text = display(node, info.generic_params)
        name = qualified(node[1] if node[0] == "gen" else node) if node[0] in ("gen", "named") else ""
        target = self.links.targets.get("T:" + name)
        if target is None:
            return code_span(text)
        where = "" if target[0] == page else target[0]
        return "[" + code_span(text) + "](" + where + "#" + target[1] + ")"

    def render_enum(self, info, renderer):
        out = ["| Name | Value | Description |", "|---|---|---|"]
        values = [m for m in info.members if m.kind == "enumvalue" and m.visible]
        values.sort(key=lambda m: (_sort_number(m.value), m.name))
        for m in values:
            element, _ = self.doc_of(m.doc_id)
            text = renderer.render(element.find("summary")) if element is not None else ""
            value = str(m.value[1]) if m.value else ""
            anchor = '<a id="' + m.anchor + '"></a>'
            out.append("| " + anchor + code_span(m.name) + " | " + value + " | " + table_cell(text) + " |")
        out.append("")
        return out

    def render_member(self, info, m, renderer):
        out = ['<a id="' + m.anchor + '"></a>', "", "### `" + member_signature(info, m) + "`", ""]
        deprecated = self.deprecation(m.attributes)
        if deprecated:
            out.extend(["> " + deprecated, ""])
        element, unresolved = self.doc_of(m.doc_id, info, m)
        if element is None:
            out.extend(["*Not documented.*", ""])
            return out
        out.extend(self.render_sections(element, renderer, unresolved))
        return out

    def render_sections(self, element, renderer, unresolved):
        out = []
        if element is None:
            return ["*No summary.*", ""]
        summary = renderer.render(element.find("summary"))
        if summary:
            out.extend([summary, ""])
        elif unresolved == "dotnet":
            out.extend(["*A standard .NET member (an override or an interface implementation); see the .NET documentation.*", ""])
        elif unresolved:
            out.extend(["*Inherits the documentation of the member it overrides or implements, which has none yet.*", ""])
        remarks = renderer.render(element.find("remarks"))
        if remarks:
            out.extend([remarks, ""])
        for tag, title in (("typeparam", "Type parameters"), ("param", "Parameters")):
            items = element.findall(tag)
            if items:
                out.extend(["**" + title + "**", ""])
                for item in items:
                    text = renderer.render(item).replace("\n\n", " ")
                    out.append("- " + code_span(item.get("name")) + ": " + text)
                out.append("")
        for tag, title in (("returns", "Returns"), ("value", "Value")):
            text = renderer.render(element.find(tag))
            if text:
                out.extend(["**" + title + ":** " + text, ""])
        exceptions = element.findall("exception")
        if exceptions:
            out.extend(["**Exceptions**", ""])
            for item in exceptions:
                out.append("- " + self.links.cref(item.get("cref"), renderer.page) + ": " +
                           renderer.render(item).replace("\n\n", " "))
            out.append("")
        for example in element.findall("example"):
            text = renderer.render(example)
            if text:
                out.extend(["**Example**", "", text, ""])
        return out

