class Links:
    """Where each rendered type and member lives: doc ID -> (page, anchor, display text)."""

    def __init__(self):
        self.targets = {}
        self.type_names = {}

    def add(self, doc_id, page, anchor, text):
        self.targets[doc_id] = (page, anchor, text)

    def cref(self, cref, page):
        """Markdown for a cref: a link when the target is rendered, else a code span."""
        cref = cref or ""
        if cref.startswith("!:"):
            cref = cref[2:]
        target = self.targets.get(cref)
        text = target[2] if target else self.short(cref)
        if target is None:
            return code_span(text)
        where = "" if target[0] == page else target[0]
        return "[" + code_span(text) + "](" + where + "#" + target[1] + ")"

    def short(self, cref):
        """A readable name for a cref that is not rendered (internal, or outside our assemblies)."""
        body = cref.split(":", 1)[1] if ":" in cref[:2] else cref
        kind = cref[:1] if ":" in cref[:2] else "T"
        body = body.split("(", 1)[0].split("~", 1)[0]
        body = re.sub(r"``\d+$", "", body)
        if kind == "T":
            full = body
            if full in self.type_names:
                return self.type_names[full]
            return strip_arity(full.rsplit(".", 1)[-1])
        owner, _, member = body.rpartition(".")
        owner_text = self.type_names.get(owner, strip_arity(owner.rsplit(".", 1)[-1]))
        member = member.replace("#ctor", "constructor")
        return owner_text + "." + member


def code_span(text):
    text = text or ""
    if "`" in text:
        return "`` " + text + " ``"
    return "`" + text + "`"


def escape_text(text):
    out = []
    for ch in text:
        if ch in "\\*_[]`|":
            out.append("\\" + ch)
        elif ch == "<":
            out.append("&lt;")
        elif ch == ">":
            out.append("&gt;")
        else:
            out.append(ch)
    return "".join(out)


def plain_text(element):
    """All text inside an element, tags dropped (for <c> and <code>)."""
    return "".join(element.itertext())


class DocRenderer:
    def __init__(self, links, page, plain=False):
        self.links = links
        self.page = page
        self.plain = plain        # True: cross-references as code spans, no links (table cells)
        self.code_blocks = []

    def render(self, element):
        """Markdown for the content of one documentation element (summary, remarks, ...)."""
        if element is None:
            return ""
        self.code_blocks = []
        raw = self._content(element)
        raw = re.sub(r"[ \t\r\n]+", " ", raw)
        raw = raw.replace(LINE + " ", LINE).replace(" " + LINE, LINE)
        paragraphs = []
        for block in raw.split(PARA):
            block = block.strip(" ").replace(LINE, "\n")
            if block.strip():
                paragraphs.append(block.strip())
        text = "\n\n".join(paragraphs)
        for i, code in enumerate(self.code_blocks):
            text = text.replace(CODE + str(i) + CODE, "```csharp\n" + code + "\n```")
        return text

    def _content(self, element):
        parts = [escape_text(element.text or "")]
        for child in element:
            parts.append(self._child(child))
            parts.append(escape_text(child.tail or ""))
        return "".join(parts)

    def _child(self, child):
        tag = child.tag
        if tag == "c":
            return code_span(re.sub(r"\s+", " ", plain_text(child)).strip())
        if tag == "code":
            self.code_blocks.append(_dedent(plain_text(child)))
            return PARA + CODE + str(len(self.code_blocks) - 1) + CODE + PARA
        if tag == "para":
            return PARA + self._content(child) + PARA
        if tag in ("b", "strong"):
            return "**" + self._content(child).strip() + "**"
        if tag in ("i", "em"):
            return "*" + self._content(child).strip() + "*"
        if tag in ("see", "seealso"):
            if child.get("langword"):
                return code_span(child.get("langword"))
            if child.get("href"):
                label = self._content(child).strip() or child.get("href")
                return label if self.plain else "[" + label + "](" + child.get("href") + ")"
            if self.plain:
                return code_span(self.links.short(child.get("cref") or ""))
            return self.links.cref(child.get("cref"), self.page)
        if tag in ("paramref", "typeparamref"):
            return code_span(child.get("name"))
        if tag == "br":
            return LINE
        if tag == "list":
            return self._list(child)
        if tag == "inheritdoc":
            return ""
        return self._content(child)

    def _list(self, element):
        numbered = element.get("type") == "number"
        lines = []
        for n, item in enumerate(element.findall("item"), start=1):
            term = item.find("term")
            description = item.find("description")
            if description is None and term is None:
                text = self._content(item).strip()
            else:
                text = ""
                if term is not None:
                    text = "**" + self._content(term).strip() + "**"
                if description is not None:
                    body = self._content(description).strip()
                    text = text + ": " + body if text else body
            text = text.replace(PARA, " ")
            lines.append(("%d. " % n if numbered else "- ") + text)
        return PARA + LINE.join(lines) + PARA


def _dedent(code):
    lines = code.strip("\n").split("\n")
    widths = [len(l) - len(l.lstrip(" ")) for l in lines if l.strip()]
    cut = min(widths) if widths else 0
    return "\n".join(l[cut:] for l in lines).rstrip()


def load_xml(path):
    """doc ID -> <member> element."""
    members = {}
    for member in ET.parse(path).getroot().iter("member"):
        members[member.get("name")] = member
    return members


