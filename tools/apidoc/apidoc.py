class TypeInfo:
    def __init__(self):
        self.assembly = ""
        self.namespace = ""
        self.names = ()          # outermost first, with metadata arity suffixes
        self.flags = 0
        self.extends = None      # type node or None
        self.interfaces = []     # type nodes
        self.kind = "class"
        self.visible = False
        self.generic_params = []
        self.generic_constraints = {}
        self.members = []
        self.attributes = []     # (attribute type name, decoded arguments)
        self.delegate_invoke = None
        self.compiler_generated = False

    @property
    def full_name(self):
        return (self.namespace + "." if self.namespace else "") + ".".join(self.names)

    @property
    def doc_id(self):
        return "T:" + self.full_name

    @property
    def display_name(self):
        """Outer<T>.Inner, with the generic parameter names this type declares."""
        parts, used = [], 0
        for name in self.names:
            match = ARITY.match(name)
            if match:
                count = int(match.group(2))
                parts.append(match.group(1) + "<" + ", ".join(self.generic_params[used:used + count]) + ">")
                used += count
            else:
                parts.append(name)
        return ".".join(parts)

    @property
    def is_sealed(self):
        return bool(self.flags & 0x100)


class MemberInfo:
    def __init__(self, kind, name):
        self.kind = kind          # ctor, method, property, field, event, enumvalue
        self.name = name
        self.doc_id = ""
        self.signature = ""       # C#-like, one line
        self.visible = False
        self.compiler_generated = False
        self.param_count = 0
        self.attributes = []
        self.value = None         # constant text for fields and enum values
        self.types = []           # type nodes it mentions (for the mod-API closure)
        self.overload_key = ""    # for anchors of overloads


class Assembly:
    """One assembly's public surface, built from its metadata."""

    def __init__(self, path):
        self.path = path
        self.md = Metadata(path)
        md = self.md
        self.name = md.string(md.rows[ASSEMBLY][0][7]) if md.rows[ASSEMBLY] else os.path.splitext(os.path.basename(path))[0]
        self._typeref_cache = {}
        self._typedef_names = {}
        self.enclosing = {}
        for nested, outer in md.rows[NESTEDCLASS]:
            self.enclosing[nested] = outer

        # Member lists of each type: TypeDef rows own contiguous runs of fields and methods, and
        # PropertyMap/EventMap rows own contiguous runs of properties and events (II.22.37).
        self.method_owner = {}
        self.fields_of = {}
        self.methods_of = {}
        typedefs = md.rows[TYPEDEF]
        for i, row in enumerate(typedefs, start=1):
            next_row = typedefs[i] if i < len(typedefs) else None
            field_end = next_row[4] if next_row else len(md.rows[FIELD]) + 1
            method_end = next_row[5] if next_row else len(md.rows[METHODDEF]) + 1
            self.fields_of[i] = list(range(row[4], field_end))
            self.methods_of[i] = list(range(row[5], method_end))
            for m in self.methods_of[i]:
                self.method_owner[m] = i
        self.properties_of = self._runs(PROPERTYMAP, PROPERTY)
        self.events_of = self._runs(EVENTMAP, EVENT)

        self.generic_params = {}   # (table, row) -> [(number, name, gp row index)]
        for gp_index, (number, flags, owner, name) in enumerate(md.rows[GENERICPARAM], start=1):
            key = Metadata.decode("TypeOrMethodDef", owner)
            self.generic_params.setdefault(key, []).append((number, md.string(name), gp_index, flags))
        for key in self.generic_params:
            self.generic_params[key].sort()
        self.gp_constraints = {}
        for owner, constraint in md.rows[GENERICPARAMCONSTRAINT]:
            self.gp_constraints.setdefault(owner, []).append(Metadata.decode("TypeDefOrRef", constraint))

        self.constants = {}
        for type_word, parent, value in md.rows[CONSTANT]:
            self.constants[Metadata.decode("HasConstant", parent)] = (type_word & 0xFF, md.blob(value))

        self.attributes = {}
        for parent, ctor, value in md.rows[CUSTOMATTRIBUTE]:
            key = Metadata.decode("HasCustomAttribute", parent)
            self.attributes.setdefault(key, []).append((Metadata.decode("CustomAttributeType", ctor), value))

        self.semantics = {}        # method row -> (flags, (table, row))
        self.accessors = {}        # (table, row) -> [(flags, method row)]
        for flags, method, association in md.rows[METHODSEMANTICS]:
            target = Metadata.decode("HasSemantics", association)
            self.semantics[method] = (flags, target)
            self.accessors.setdefault(target, []).append((flags, method))

        self.interfaces = {}
        for cls, iface in md.rows[INTERFACEIMPL]:
            self.interfaces.setdefault(cls, []).append(Metadata.decode("TypeDefOrRef", iface))
        self.types = []

    def collect_enums(self, into):
        """Adds {enum full name: {value: member name}} of this assembly's enums, for default values."""
        for i, row in enumerate(self.md.rows[TYPEDEF], start=1):
            table, base = Metadata.decode("TypeDefOrRef", row[3])
            if not base or table == TYPESPEC or qualified(self.type_of_token((table, base))) != "System.Enum":
                continue
            values = into.setdefault(qualified(self.typedef_named(i)), {})
            for f in self.fields_of.get(i, []):
                flags, name_index, _ = self.md.row(FIELD, f)
                constant = self.constant_value((FIELD, f))
                if flags & 0x40 and constant is not None:
                    values.setdefault(constant[1], self.md.string(name_index))

    def build_types(self):
        """Builds every type's model. Call after every assembly's collect_enums."""
        self.types = []
        for i in range(1, len(self.md.rows[TYPEDEF]) + 1):
            info = self._build_type(i)
            if info is not None:
                self.types.append(info)

    def _runs(self, map_table, target_table):
        """{type row: [target rows]} from a PropertyMap or EventMap table."""
        rows = self.md.rows[map_table]
        runs = {}
        for i, (parent, start) in enumerate(rows):
            end = rows[i + 1][1] if i + 1 < len(rows) else len(self.md.rows[target_table]) + 1
            runs[parent] = list(range(start, end))
        return runs

    # -- names ------------------------------------------------------------------------------

    def typedef_named(self, index):
        if index not in self._typedef_names:
            row = self.md.row(TYPEDEF, index)
            name, namespace = self.md.string(row[1]), self.md.string(row[2])
            if index in self.enclosing:
                outer = self.typedef_named(self.enclosing[index])
                self._typedef_names[index] = ("named", outer[1], outer[2] + (name,))
            else:
                self._typedef_names[index] = ("named", namespace, (name,))
        return self._typedef_names[index]

    def typeref_named(self, index):
        if index not in self._typeref_cache:
            scope, name, namespace = self.md.row(TYPEREF, index)
            table, row = Metadata.decode("ResolutionScope", scope)
            if table == TYPEREF and row:
                outer = self.typeref_named(row)
                self._typeref_cache[index] = ("named", outer[1], outer[2] + (self.md.string(name),))
            else:
                self._typeref_cache[index] = ("named", self.md.string(namespace), (self.md.string(name),))
        return self._typeref_cache[index]

    def type_of_token(self, token):
        table, index = token
        if table == TYPEDEF:
            return self.typedef_named(index)
        if table == TYPEREF:
            return self.typeref_named(index)
        return self.read_type(SigReader(self.md.blob(self.md.row(TYPESPEC, index)[0])))

    # -- signatures -------------------------------------------------------------------------

    def read_type(self, sig, modifiers=None):
        while True:
            element = sig.byte()
            if element in (0x1F, 0x20):          # CMOD_REQD, CMOD_OPT
                named = self.type_of_token(sig.token())
                if modifiers is not None:
                    modifiers.append(qualified(named) if named[0] == "named" else "")
                continue
            if element == 0x45:                  # PINNED
                continue
            break
        if element in PRIMITIVES:
            return ("prim", PRIMITIVES[element])
        if element in (0x11, 0x12):              # VALUETYPE, CLASS; remember which, for default values
            node = self.type_of_token(sig.token())
            return node + (element == 0x11,) if node[0] == "named" else node
        if element == 0x0F:
            return ("ptr", self.read_type(sig))
        if element == 0x10:
            return ("ref", self.read_type(sig))
        if element == 0x1D:
            return ("arr", self.read_type(sig), 0)
        if element == 0x14:                      # ARRAY: type, rank, sizes, lower bounds
            inner = self.read_type(sig)
            rank = sig.uint()
            for _ in range(sig.uint()):
                sig.uint()
            for _ in range(sig.uint()):
                sig.uint()
            return ("arr", inner, rank)
        if element == 0x15:                      # GENERICINST
            is_value_type = sig.byte() == 0x11
            base = self.type_of_token(sig.token()) + (is_value_type,)
            return ("gen", base, [self.read_type(sig) for _ in range(sig.uint())])
        if element == 0x13:
            return ("var", sig.uint())
        if element == 0x1E:
            return ("mvar", sig.uint())
        if element == 0x1B:                      # function pointer
            self.read_method_sig(sig)
            return ("prim", "System.IntPtr")
        raise ValueError("%s: unsupported element type 0x%02x" % (self.path, element))

    def read_method_sig(self, sig):
        convention = sig.byte()
        generic_count = sig.uint() if convention & 0x10 else 0
        count = sig.uint()
        return_modifiers = []
        returns = self.read_type(sig, return_modifiers)
        params = []
        for _ in range(count):
            if sig.peek() == 0x41:               # SENTINEL (varargs)
                sig.byte()
            params.append(self.read_type(sig))
        return generic_count, returns, params, return_modifiers

    # -- attributes and constants ------------------------------------------------------------

    def attribute_type(self, ctor):
        table, index = ctor
        if table == METHODDEF:
            return self.typedef_named(self.method_owner[index])
        if table == MEMBERREF:
            parent, _, _ = self.md.row(MEMBERREF, index)
            ptable, prow = Metadata.decode("MemberRefParent", parent)
            if ptable == TYPEREF:
                return self.typeref_named(prow)
            if ptable == TYPEDEF:
                return self.typedef_named(prow)
            if ptable == TYPESPEC:
                node = self.read_type(SigReader(self.md.blob(self.md.row(TYPESPEC, prow)[0])))
                return node[1] if node[0] == "gen" else node
        return ("named", "", ("?",))

    def attribute_ctor_params(self, ctor):
        table, index = ctor
        blob = self.md.row(METHODDEF, index)[4] if table == METHODDEF else self.md.row(MEMBERREF, index)[2]
        return self.read_method_sig(SigReader(self.md.blob(blob)))[2]

    def attributes_of(self, table, index):
        """[(attribute type name, [fixed args], {named args})] for one metadata row."""
        found = []
        for ctor, value in self.attributes.get((table, index), []):
            name = qualified(self.attribute_type(ctor))
            args, named = [], {}
            if name in (ATTR_OBSOLETE, ATTR_CWY_DEPRECATED):
                args, named = self._decode_attribute(ctor, self.md.blob(value))
            found.append((name, args, named))
        return found

    def _decode_attribute(self, ctor, blob):
        """Fixed and named arguments of string, bool and int/enum types; stops at anything else."""
        reader = SigReader(blob)
        args, named = [], {}
        try:
            if reader.byte() != 0x01 or reader.byte() != 0x00:
                return args, named
            for param in self.attribute_ctor_params(ctor):
                if param == ("prim", "System.String"):
                    args.append(_ser_string(reader))
                elif param == ("prim", "System.Boolean"):
                    args.append(reader.byte() != 0)
                elif param == ("prim", "System.Int32") or param[0] == "named":
                    args.append(struct.unpack_from("<i", reader.b, reader.p)[0])
                    reader.p += 4
                else:
                    return args, named
            count = reader.byte() | (reader.byte() << 8)
            for _ in range(count):
                reader.byte()                    # FIELD or PROPERTY
                kind = reader.byte()
                if kind == 0x55:                 # enum: its type name first
                    _ser_string(reader)
                key = _ser_string(reader)
                if kind == 0x0E:
                    named[key] = _ser_string(reader)
                elif kind == 0x02:
                    named[key] = reader.byte() != 0
                elif kind in (0x08, 0x55):
                    named[key] = struct.unpack_from("<i", reader.b, reader.p)[0]
                    reader.p += 4
                else:
                    break
        except (IndexError, struct.error) as error:
            print("apidoc: %s: could not read the arguments of an attribute (%s); using what was read"
                  % (self.path, error), file=sys.stderr)
        return args, named

    def has_attribute(self, table, index, name):
        for ctor, _ in self.attributes.get((table, index), []):
            if qualified(self.attribute_type(ctor)) == name:
                return True
        return False

    def constant_value(self, key):
        """(element type, python value) of a Constant row, or None."""
        if key not in self.constants:
            return None
        element, blob = self.constants[key]
        formats = {0x02: "<?", 0x03: "<H", 0x04: "<b", 0x05: "<B", 0x06: "<h", 0x07: "<H", 0x08: "<i",
                   0x09: "<I", 0x0A: "<q", 0x0B: "<Q", 0x0C: "<f", 0x0D: "<d"}
        if element in formats:
            value = struct.unpack_from(formats[element], blob, 0)[0]
            if element == 0x03:
                value = chr(value)
            return element, value
        if element == 0x0E:
            return element, blob.decode("utf-16-le")
        return element, None                   # 0x12: a null reference

    # -- building -----------------------------------------------------------------------------

    def _build_type(self, index):
        md = self.md
        flags, name_index, namespace_index, extends, _, _ = md.row(TYPEDEF, index)
        name = md.string(name_index)
        if name == "<Module>":
            return None
        info = TypeInfo()
        info.assembly = self.name
        named = self.typedef_named(index)
        info.namespace, info.names = named[1], named[2]
        info.flags = flags
        ext_table, ext_row = Metadata.decode("TypeDefOrRef", extends)
        info.extends = self.type_of_token((ext_table, ext_row)) if ext_row else None
        info.interfaces = [self.type_of_token(t) for t in self.interfaces.get(index, [])]
        info.generic_params = [n for _, n, _, _ in self.generic_params.get((TYPEDEF, index), [])]
        info.generic_constraints = self._constraints((TYPEDEF, index), info.generic_params, ())
        info.visible = self._type_visible(index)
        info.compiler_generated = "<" in name or self.has_attribute(TYPEDEF, index, ATTR_COMPILER_GENERATED)
        info.attributes = self.attributes_of(TYPEDEF, index)
        info.kind = self._kind(info, index)
        info.members = self._members(info, index)
        return info

    def _type_visible(self, index):
        visibility = self.md.row(TYPEDEF, index)[0] & 0x7
        if index in self.enclosing:
            return visibility in (VIS_NESTED_PUBLIC, VIS_NESTED_FAMILY, VIS_NESTED_FAM_OR_ASSEM) and \
                self._type_visible(self.enclosing[index])
        return visibility == VIS_PUBLIC

    def _kind(self, info, index):
        if info.flags & 0x20:
            return "interface"
        base = qualified(info.extends) if info.extends and info.extends[0] == "named" else ""
        if base == "System.Enum":
            return "enum"
        if base == "System.ValueType":
            return "struct"
        if base == "System.MulticastDelegate":
            return "delegate"
        abstract, sealed = bool(info.flags & 0x80), bool(info.flags & 0x100)
        if abstract and sealed:
            return "static class"
        method_names = {self.md.string(self.md.row(METHODDEF, m)[3]) for m in self.methods_of.get(index, [])}
        word = "record" if "<Clone>$" in method_names else "class"
        if abstract:
            return "abstract " + word
        if sealed:
            return "sealed " + word
        return word

    def _constraints(self, owner, type_params, method_params):
        """{parameter name: ["class", "ICwyEvent", "new()"]}."""
        result = {}
        for number, name, gp_index, flags in self.generic_params.get(owner, []):
            parts = []
            if flags & 0x04:
                parts.append("class")
            if flags & 0x08:
                parts.append("struct")
            for token in self.gp_constraints.get(gp_index, []):
                node = self.type_of_token(token)
                if node[0] == "named" and qualified(node) == "System.ValueType" and "struct" in parts:
                    continue
                parts.append(display(node, type_params, method_params))
            if flags & 0x10 and "struct" not in parts:
                parts.append("new()")
            if parts:
                result[name] = parts
        return result

    def _member_visible(self, info, access):
        if not info.visible:
            return False
        if access == ACCESS_PUBLIC:
            return True
        return access in (ACCESS_FAMILY, ACCESS_FAM_OR_ASSEM) and not info.is_sealed

    def _members(self, info, index):
        md = self.md
        members = []
        type_params = info.generic_params
        type_id = info.full_name

        # Fields.
        for f in self.fields_of.get(index, []):
            flags, name_index, sig_index = md.row(FIELD, f)
            name = md.string(name_index)
            if flags & 0x400:                    # RTSpecialName: an enum's value__
                continue
            sig = SigReader(md.blob(sig_index))
            sig.byte()
            field_type = self.read_type(sig)
            member = MemberInfo("enumvalue" if info.kind == "enum" else "field", name)
            member.doc_id = "F:" + type_id + "." + name
            member.visible = self._member_visible(info, flags & 0x7)
            member.compiler_generated = "<" in name or self.has_attribute(FIELD, f, ATTR_COMPILER_GENERATED)
            member.attributes = self.attributes_of(FIELD, f)
            member.types = [field_type]
            constant = self.constant_value((FIELD, f))
            if constant is not None:
                member.value = constant
            words = []
            if flags & 0x7 in (ACCESS_FAMILY, ACCESS_FAM_OR_ASSEM):
                words.append("protected")
            if flags & 0x40:
                words.append("const")
            else:
                if flags & 0x10:
                    words.append("static")
                if flags & 0x20:
                    words.append("readonly")
            member.signature_parts = (words, display(field_type, type_params), name)
            members.append(member)

        # Methods (accessors are folded into their property or event below).
        for m in self.methods_of.get(index, []):
            _, _, flags, name_index, sig_index, _ = md.row(METHODDEF, m)
            name = md.string(name_index)
            if m in self.semantics:
                continue
            generic_count, returns, params, _ = self.read_method_sig(SigReader(md.blob(sig_index)))
            method_params = [n for _, n, _, _ in self.generic_params.get((METHODDEF, m), [])]
            is_ctor = name in (".ctor", ".cctor")
            member = MemberInfo("ctor" if is_ctor else "method", name)
            doc_name = name.replace(".", "#").replace("<", "{").replace(">", "}").replace(",", "@")
            member.doc_id = "M:" + type_id + "." + doc_name
            if generic_count:
                member.doc_id += "``%d" % generic_count
            if params:
                member.doc_id += "(" + ",".join(id_string(p) for p in params) + ")"
            if name in ("op_Implicit", "op_Explicit"):
                member.doc_id += "~" + id_string(returns)
            member.visible = self._member_visible(info, flags & 0x7) and name != ".cctor"
            member.compiler_generated = "<" in name or self.has_attribute(METHODDEF, m, ATTR_COMPILER_GENERATED)
            member.attributes = self.attributes_of(METHODDEF, m)
            member.param_count = len(params)
            member.types = [returns] + list(params)
            member.overload_key = ",".join(display(p, type_params, method_params) for p in params)
            member.signature = self._method_signature(info, m, flags, name, returns, params, method_params)
            members.append(member)

        # Properties.
        for p_index in self.properties_of.get(index, []):
            _, name_index, sig_index = md.row(PROPERTY, p_index)
            name = md.string(name_index)
            sig = SigReader(md.blob(sig_index))
            sig.byte()
            count = sig.uint()
            property_type = self.read_type(sig)
            params = [self.read_type(sig) for _ in range(count)]
            member = MemberInfo("property", name)
            member.doc_id = "P:" + type_id + "." + name.replace(".", "#")
            if params:
                member.doc_id += "(" + ",".join(id_string(p) for p in params) + ")"
            accessors = self.accessors.get((PROPERTY, p_index), [])
            member.visible, words, parts = self._accessor_words(info, accessors, getter=0x2, setter=0x1)
            member.compiler_generated = self.has_attribute(PROPERTY, p_index, ATTR_COMPILER_GENERATED)
            member.attributes = self.attributes_of(PROPERTY, p_index)
            member.param_count = len(params)
            member.types = [property_type] + params
            member.overload_key = ",".join(display(p, type_params) for p in params)
            shown = "this[" + ", ".join(display(p, type_params) for p in params) + "]" if params else name
            member.signature = " ".join(words + [display(property_type, type_params), shown]) + " { " + " ".join(parts) + " }"
            members.append(member)

        # Events.
        for e_index in self.events_of.get(index, []):
            _, name_index, event_type = md.row(EVENT, e_index)
            name = md.string(name_index)
            handler = self.type_of_token(Metadata.decode("TypeDefOrRef", event_type))
            member = MemberInfo("event", name)
            member.doc_id = "E:" + type_id + "." + name.replace(".", "#")
            accessors = self.accessors.get((EVENT, e_index), [])
            member.visible, words, _ = self._accessor_words(info, accessors, getter=0x8, setter=0x10)
            member.attributes = self.attributes_of(EVENT, e_index)
            member.types = [handler]
            member.signature = " ".join(words + ["event", display(handler, type_params), name])
            members.append(member)

        if info.kind == "delegate":
            for member in members:
                if member.name == "Invoke":
                    info.delegate_invoke = member
        return members

    def _accessor_words(self, info, accessors, getter, setter):
        """(visible, modifier words, accessor words) of a property or event from its accessor methods."""
        visible = False
        words, parts = [], []
        is_static = False
        modifier = ""
        for semantics, method in sorted(accessors, key=lambda a: (0 if a[0] & getter else 1, a[1])):
            _, _, flags, _, sig_index, _ = self.md.row(METHODDEF, method)
            accessor_visible = self._member_visible(info, flags & 0x7)
            if flags & 0x10:
                is_static = True
            if not modifier:
                modifier = _virtual_word(flags, info.kind == "interface")
            if not accessor_visible:
                continue
            visible = True
            if semantics & getter:
                parts.append("get;")
            elif semantics & setter:
                _, _, _, modifiers = self.read_method_sig(SigReader(self.md.blob(sig_index)))
                is_init = any(m.endswith("IsExternalInit") for m in modifiers)
                parts.append("init;" if is_init else "set;")
            if flags & 0x7 in (ACCESS_FAMILY, ACCESS_FAM_OR_ASSEM) and "protected" not in words:
                words.append("protected")
        if is_static:
            words.append("static")
        elif modifier:
            words.append(modifier)
        return visible, words, parts

    def _method_signature(self, info, method, flags, name, returns, params, method_params):
        type_params = info.generic_params
        words = []
        if flags & 0x7 in (ACCESS_FAMILY, ACCESS_FAM_OR_ASSEM):
            words.append("protected")
        if flags & 0x10:
            words.append("static")
        else:
            word = _virtual_word(flags, info.kind == "interface")
            if word:
                words.append(word)

        param_rows = self._param_rows(method)
        is_extension = self.has_attribute(METHODDEF, method, ATTR_EXTENSION)
        rendered = []
        for position, node in enumerate(params, start=1):
            row = param_rows.get(position)
            pname = self.md.string(row[1][2]) if row else "arg%d" % position
            pflags = row[1][0] if row else 0
            text = display(node, type_params, method_params)
            if node[0] == "ref":
                inner = display(node[1], type_params, method_params)
                text = ("out " if pflags & 0x2 and not pflags & 0x1 else "in " if pflags & 0x1 else "ref ") + inner
            if row and self.has_attribute(PARAM, row[0], ATTR_PARAM_ARRAY):
                text = "params " + text
            if position == 1 and is_extension:
                text = "this " + text
            text += " " + pname
            if row and pflags & 0x1000:
                text += " = " + self.format_constant(self.constant_value((PARAM, row[0])), node)
            rendered.append(text)

        generic = ""
        if method_params:
            generic = "<" + ", ".join(method_params) + ">"
        constraints = self._constraints((METHODDEF, method), type_params, method_params)
        where = "".join(" where " + p + " : " + ", ".join(c) for p, c in constraints.items())

        if name == ".ctor":
            head = strip_arity(info.names[-1])
            return " ".join(words + [head + "(" + ", ".join(rendered) + ")"])
        if name in OPERATORS:
            symbol = OPERATORS[name]
            if name in ("op_Implicit", "op_Explicit"):
                return " ".join(words + [symbol, "operator", display(returns, type_params, method_params) +
                                         "(" + ", ".join(rendered) + ")"])
            return " ".join(words + [display(returns, type_params, method_params),
                                     "operator " + symbol + "(" + ", ".join(rendered) + ")"])
        return " ".join(words + [display(returns, type_params, method_params),
                                 name + generic + "(" + ", ".join(rendered) + ")" + where])

    def _param_rows(self, method):
        rows = self.md.rows[METHODDEF]
        start = rows[method - 1][5]
        end = rows[method][5] if method < len(rows) else len(self.md.rows[PARAM]) + 1
        found = {}
        for p in range(start, end):
            row = self.md.row(PARAM, p)
            found[row[1]] = (p, row)
        return found

    def format_constant(self, constant, node):
        if constant is None:
            return "default"
        element, value = constant
        if element == 0x12 or value is None:
            # A struct parameter's `= default` is stored as a null reference too.
            named = node[1] if node[0] == "gen" else node
            if node[0] == "gen" and qualified(named) == "System.Nullable`1":
                return "null"
            if named[0] == "named" and len(named) > 3 and named[3]:
                return "default"
            return "null"
        if element == 0x0E:
            return _csharp_string(value)
        if element == 0x02:
            return "true" if value else "false"
        if element == 0x03:
            return "'" + value + "'"
        if element in (0x0C, 0x0D):
            return _float_text(element, value)
        enum_name = ENUM_NAMES.get(qualified(node)) if node[0] == "named" else None
        if enum_name and value in enum_name:
            return strip_arity(node[2][-1]) + "." + enum_name[value]
        return str(value)


OPERATORS = {
    "op_Equality": "==", "op_Inequality": "!=", "op_LessThan": "<", "op_GreaterThan": ">",
    "op_LessThanOrEqual": "<=", "op_GreaterThanOrEqual": ">=", "op_Addition": "+",
    "op_Subtraction": "-", "op_Multiply": "*", "op_Division": "/", "op_Modulus": "%",
    "op_UnaryNegation": "-", "op_UnaryPlus": "+", "op_LogicalNot": "!", "op_BitwiseAnd": "&",
    "op_BitwiseOr": "|", "op_ExclusiveOr": "^", "op_OnesComplement": "~", "op_True": "true",
    "op_False": "false", "op_Increment": "++", "op_Decrement": "--", "op_Implicit": "implicit",
    "op_Explicit": "explicit",
}

# Enum member names by value, filled once every assembly is read, for default values.
ENUM_NAMES = {}


def _virtual_word(flags, in_interface):
    """static/abstract/virtual/override for a method's flags; nothing inside an interface."""
    if in_interface:
        return ""
    if flags & 0x400:
        return "abstract"
    if flags & 0x40:
        new_slot, final = bool(flags & 0x100), bool(flags & 0x20)
        if new_slot:
            return "" if final else "virtual"
        return "sealed override" if final else "override"
    return ""


def _float_text(element, value):
    """C# spelling of a float (shortest text that reads back to the same float32, with f) or double."""
    if element == 0x0D:
        return repr(value)
    exact = struct.pack("<f", value)
    for digits in range(1, 10):
        text = "%.*g" % (digits, value)
        if struct.pack("<f", float(text)) == exact:
            break
    return repr(float(text)) + "f"   # repr of the short decimal: 120.0, 0.6, 0.01


def _ser_string(reader):
    if reader.peek() == 0xFF:
        reader.byte()
        return None
    length = reader.uint()
    value = bytes(reader.b[reader.p:reader.p + length]).decode("utf-8")
    reader.p += length
    return value


def _csharp_string(value):
    escaped = value.replace("\\", "\\\\").replace("\"", "\\\"").replace("\n", "\\n").replace("\r", "\\r").replace("\t", "\\t")
    return "\"" + escaped + "\""


