#!/usr/bin/env python3
"""CWY:LS Mod Loader API reference generator (Python 3 standard library only).

For every assembly given on the command line it reads two files:

* the compiler's XML documentation file next to it (``<Name>.xml``, written when the project is
  built with ``-p:GenerateDocumentationFile=true``): the text of every ``///`` comment;
* the assembly itself, as bytes: its ECMA-335 metadata tables (types, members, signatures,
  visibility, constants, attributes). No .NET runtime and no reflection are involved.

Why both: the C# compiler also writes the ``///`` comments of internal and private members into
the XML file, and the XML has no visibility information. The metadata decides what a mod can
see (public, or protected on a type it can derive from) and gives each member its exact
signature; the XML gives the words. A member whose documentation ID has no ``<member>`` entry is
reported as not documented.

Output (``--out``, normally ``docs/api``): one page per namespace (``<Namespace>.md``), an index
(``README.md``) and ``undocumented.md``. Every generated file starts with a marker comment; files
with that marker that a run no longer produces are deleted, nothing else in the folder is touched.
The output is deterministic: the same assemblies give byte-identical files.

Usage (see tools/apidoc/README.md for the one-command wrapper):

    python3 tools/apidoc/apidoc.py --out docs/api <bin>/CwyLs.ModLoader.dll <bin>/CwyLs.ModLoader.Core.dll
    python3 tools/apidoc/apidoc.py --check --out docs/api ...   # exit 1 when docs/api is stale
"""

